def decode(v):
    typ = v & 0x7; fi = (v >> 3) & 0x1ff; gi = (v >> 12) & 0xff
    qi = (v >> 20) & 0x7f; si = (v >> 27) & 0x1f
    fhz = PEQ_FREQ_TABLE[fi] if fi < len(PEQ_FREQ_TABLE) else fi
    db = -24 + gi * 0.2
    tnames = {0: 'PEAK', 1: 'LOW_SH', 2: 'HIGH_SH'}
    return f"{tnames.get(typ,typ)} {fhz:>6}Hz {db:>+5.1f}dB q{qi} s{si} (gIdx{gi})"

