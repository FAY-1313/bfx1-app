// 双语选框固定宽度: 按 en/zh 两文本较长者算恒定 minWidth (切换语言选框不变宽)
// en 拉丁字符 ~0.62em + 字距; zh 全角 ~1em + 字距; padX 为左右 padding
export function langBoxMinWidth(en: string, zh: string, fontSize: number, opts?: { padX?: number; lsEn?: number; lsZh?: number }): number {
  const lsEn = opts?.lsEn ?? 0.02;
  const lsZh = opts?.lsZh ?? 0.1;
  const pad = opts?.padX ?? 8;
  return Math.max(en.length * fontSize * (0.62 + lsEn), zh.length * fontSize * (1 + lsZh)) + pad * 2;
}

const STORAGE_KEY = 'bfx_lang';
/**
 * ★★ v3.62（2026-10-24 用户拍板）· 「用户手动选过语言」标记
 *
 * 用户原话：「APK 的默认语言跟随系统设定语言。」
 * 做法：只有用户**手动切换过**（双击 LOGO）才把语言钉住；否则每次启动都重新读系统语言。
 *   · bfx_lang      仅作镜像，用于兼容旧版本
 *   · bfx_lang_user 只有手动切换才写 —— 没有它就一定跟随系统
 */
const USER_KEY = 'bfx_lang_user';

interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

export const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  setLang: () => {},
  t: (key) => key,
});

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) =>
    params[k] !== undefined ? String(params[k]) : m,
  );
}

// 系统语言检测: 无用户手动偏好时, 跟随系统语言 (中文→zh, 其他→en)
function detectSystemLang(): Lang {
  try {
    /* navigator.languages 是完整偏好列表（Android WebView 常见只填第一条），
       逐个判断，任何一条是中文就按中文 —— 避免「系统中文但取了 en-US」的误判。 */
    const list = (navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || '']) as readonly string[];
    for (const item of list) {
      if (String(item).toLowerCase().startsWith('zh')) return 'zh';
    }
    /* Capacitor / Android WebView 兜底：部分机型 navigator.language 为空，
       但 navigator.userAgent 里带地区标记 */
    const ua = (navigator.userAgent || '').toLowerCase();
    if (ua.includes('zh-cn') || ua.includes('zh-hans') || ua.includes('zh_cn')) return 'zh';
    return 'en';
  } catch {
    return 'en';
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      /* 只有手动切换过（bfx_lang_user = 1）才认本地值；
         旧版本写入的 bfx_lang 也一律视为「用户手动选过」并补上标记，不丢用户选择。 */
      const userPicked = localStorage.getItem(USER_KEY) === '1';
      const stored = localStorage.getItem(STORAGE_KEY);
      if ((userPicked || stored) && (stored === 'en' || stored === 'zh')) {
        if (!userPicked) { try { localStorage.setItem(USER_KEY, '1'); } catch { /* ignore */ } }
        return stored;
      }
    } catch { /* ignore */ }
    /* 默认：每次启动跟随系统语言 */
    return detectSystemLang();
  });

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
      localStorage.setItem(USER_KEY, '1');
    } catch { /* ignore */ }
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: string, params?: Record<string, string | number>): string => {
    const value = translations[lang][key] ?? translations.en[key] ?? key;
    return interpolate(value, params);
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
