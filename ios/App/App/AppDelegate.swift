    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        // ── 屏幕常亮（对应 Android 的 FLAG_KEEP_SCREEN_ON）───────────────
        // BFX1 是调音乐器，用户会长时间盯着旋钮，熄屏会打断操作。
        UIApplication.shared.isIdleTimerDisabled = true

        // ── 音频会话：让鼓机 / 节拍器 / Looper 试听走「媒体播放」通道 ─────
        // WKWebView 里的 HTML5 音频默认受静音拨片影响（拨到静音就哑），
        // 设为 .playback + .mixWithOthers 后：静音拨片不再静音，且不打断其它 App 的音乐。
        do {
            let session = AVAudioSession.sharedInstance()
            try session.setCategory(.playback, mode: .default, options: [.mixWithOthers])
            try session.setActive(true)
        } catch {
            print("[BFX1] AVAudioSession 设置失败: \(error)")
        }
        return true
    }

